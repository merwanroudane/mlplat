@st.cache_data(show_spinner="تدريب النموذجين…", max_entries=8)
def _two_cultures(lam: float):
    X, y = two_cultures_data(n=1500, nonlinearity=lam)
    X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.4, random_state=0, stratify=y)
    import statsmodels.api as sm
    logit = sm.Logit(y_tr, sm.add_constant(X_tr)).fit(disp=0)
    p_tr = logit.predict(sm.add_constant(X_tr))
    hl, hl_p = hosmer_lemeshow(y_tr.to_numpy(), p_tr.to_numpy())
    lr = LogisticRegression(max_iter=2000).fit(X_tr, y_tr)
    rf = RandomForestClassifier(n_estimators=300, min_samples_leaf=5, random_state=0, n_jobs=1).fit(X_tr, y_tr)
    table = pd.DataFrame({"coef": logit.params, "SE": logit.bse, "p-value": logit.pvalues})
    res = {"LR acc": lr.score(X_te, y_te), "RF acc": rf.score(X_te, y_te),
           "LR AUC": roc_auc_score(y_te, lr.predict_proba(X_te)[:, 1]),
           "RF AUC": roc_auc_score(y_te, rf.predict_proba(X_te)[:, 1])}
    return table, float(hl), float(hl_p), res


